import type { Metadata } from "next";
import Image from "next/image";
import Link from "next/link";
import { notFound } from "next/navigation";
import { CheckIcon, HeartIcon } from "@phosphor-icons/react/ssr";

import { BuyButton } from "@/components/checkout/buy-button";
import { SiteHeader } from "@/components/site-header";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { Separator } from "@/components/ui/separator";
import { parseHandleSegment } from "@/lib/handle";
import { getPublicProduct } from "@/lib/dal/storefront";

const perks = [
  "Instant, protected download",
  "Secure Stripe checkout",
  "Lifetime access from your library",
];

type Params = Promise<{ handle: string; slug: string }>;

// The same cached DAL call as the page below: Next.js runs both in one
// render, and "use cache" means the database is asked only once.
async function loadProduct(params: Params) {
  const { handle: segment, slug } = await params;
  const handle = parseHandleSegment(segment);
  return handle ? getPublicProduct(handle, slug) : null;
}

// <title>, <meta description>, canonical link and Open Graph tags (S13).
// The SEO fields from the edit page win; otherwise title / description.
export async function generateMetadata({ params }: { params: Params }): Promise<Metadata> {
  const product = await loadProduct(params);
  // Missing, Draft or someone else's slug: a 404 that search engines skip.
  if (!product) return { title: "Product not found", robots: { index: false } };

  const title = product.seoTitle || product.title;
  const description = (product.seoDescription || product.description).slice(0, 160) || undefined;
  const path = `/@${product.creatorHandle}/${product.slug}`;

  return {
    title,
    description,
    // One official address per product, whatever variant was used to reach it.
    alternates: { canonical: path },
    // Link previews (WhatsApp, Facebook, LinkedIn…): the cover as the image.
    // A page's openGraph replaces the layout's (no deep merge), so the
    // shared fields are repeated here.
    openGraph: {
      siteName: "My-E-Commerce",
      type: "website",
      title,
      description,
      url: path,
      ...(product.coverUrl ? { images: [{ url: product.coverUrl, alt: product.title }] } : {}),
    },
    twitter: { card: product.coverUrl ? "summary_large_image" : "summary", title, description },
  };
}

export default async function ProductPage({
  params,
}: {
  params: Params;
}) {
  // null for an unknown creator, a slug of another creator, or a Draft → 404.
  const product = await loadProduct(params);
  if (!product) notFound();

  return (
    <div className="flex min-h-full flex-col">
      <SiteHeader />

      <main className="mx-auto grid w-full max-w-5xl flex-1 gap-10 px-4 py-10 md:grid-cols-[1.4fr_1fr]">
        <div className="flex flex-col gap-6">
          <p className="text-sm text-muted-foreground">
            <Link href={`/@${product.creatorHandle}`} className="hover:text-foreground">
              @{product.creatorHandle}
            </Link>{" "}
            / {product.slug}
          </p>
          {/* Cover uploaded on the edit page (S8); a plain panel until then. */}
          {product.coverUrl ? (
            <div className="relative aspect-16/10 overflow-hidden bg-muted">
              <Image
                src={product.coverUrl}
                alt={product.title}
                fill
                priority
                sizes="(min-width: 768px) 560px, 100vw"
                className="object-cover"
              />
            </div>
          ) : (
            <div className="flex aspect-16/10 items-center justify-center bg-muted text-xs text-muted-foreground">
              {product.type}
            </div>
          )}
          <div className="flex flex-col gap-2">
            <h1 className="font-heading text-3xl font-medium">{product.title}</h1>
            <p className="text-muted-foreground">{product.description}</p>
          </div>
          <Separator />
          {/* Per-file-type teaser generated by AI (S14). */}
          <div className="flex flex-col gap-2">
            <div className="flex items-center gap-2">
              <h2 className="font-heading font-medium">Preview</h2>
              <Badge variant="secondary">{product.type} · teaser</Badge>
            </div>
            <div className="grid grid-cols-3 gap-2">
              {[1, 2, 3].map((page) => (
                <div
                  key={page}
                  className="flex aspect-3/4 items-center justify-center bg-muted text-xs text-muted-foreground"
                >
                  page {page}
                </div>
              ))}
            </div>
            <p className="text-xs text-muted-foreground">
              First 3 pages rendered as a public teaser. Full file unlocks after
              purchase.
            </p>
          </div>
        </div>

        <aside className="md:sticky md:top-6 md:self-start">
          <Card>
            <CardContent className="flex flex-col gap-4">
              <div className="flex items-center justify-between">
                <span className="font-heading text-3xl font-medium tabular-nums">
                  {product.price}
                </span>
                <Badge>Published</Badge>
              </div>
              {/* Starts Stripe Checkout (S9): the price is read on the server. */}
              <BuyButton productId={product.id} />
              <Button size="lg" variant="outline">
                <HeartIcon />
                Save to wishlist
              </Button>
              <ul className="flex flex-col gap-2 text-sm text-muted-foreground">
                {perks.map((perk) => (
                  <li key={perk} className="flex items-center gap-2">
                    <CheckIcon className="size-4 text-primary" />
                    {perk}
                  </li>
                ))}
              </ul>
            </CardContent>
          </Card>
        </aside>
      </main>
    </div>
  );
}
